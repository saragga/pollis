/**
 * The feeds of the Oxford Academic journal at `address`, a page of academic.oup.com: its current issue, advance
 * articles and open access articles, when it has some; undefined for another address, or a journal not listed.
 */
export function findOxfordFeeds(address: string): { readonly url: string; readonly name: string }[] | undefined {
	let url: URL;
	try {
		url = new URL(address);
	} catch {
		return undefined;
	}
	const slug = url.hostname.replace(/^www\./, '') === 'academic.oup.com' ? url.pathname.split('/')[1] : undefined;
	const journal = slug && Object.hasOwn(OXFORD_JOURNALS, slug) ? OXFORD_JOURNALS[slug] : undefined;
	if (!journal) {
		return undefined;
	}
	const [id, site, name, openAccess] = journal;
	const feeds = `https://academic.oup.com/rss/site_${site}`;
	const found = [
		{ url: `${feeds}/${id}.xml`, name: `${name}: Current Issue` },
		{ url: `${feeds}/advanceAccess_${id}.xml`, name: `${name}: Advance Articles` },
	];
	if (openAccess !== false) {
		found.push({ url: `${feeds}/OpenAccess.xml`, name: `${name}: Open Access` });
	}
	return found;
}
