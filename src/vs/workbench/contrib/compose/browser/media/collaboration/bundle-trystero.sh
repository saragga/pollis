# Regenerates the vendored Trystero bundles of Compose > Collaboration: trystero-nostr.js and
# trystero-mqtt.js, ES modules the Collaboration chat and Test Connection pages load. They are
# generated, never edited by hand; the versions are pinned here and in cgmanifest.json.
# Usage: bash bundle-trystero.sh (needs npm; works in a temporary folder).

set -euo pipefail

TRYSTERO_VERSION=0.26.0
ESBUILD_VERSION=0.25.12
HERE="$(cd "$(dirname "$0")" && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

cd "$WORK"
npm init -y > /dev/null
npm install --no-audit --no-fund --save-exact \
	"@trystero-p2p/nostr@$TRYSTERO_VERSION" "@trystero-p2p/mqtt@$TRYSTERO_VERSION" "esbuild@$ESBUILD_VERSION" > /dev/null

echo "export { joinRoom, selfId, defaultRelayUrls } from '@trystero-p2p/nostr';" > nostr.mjs
echo "export { joinRoom, selfId, defaultRelayUrls } from '@trystero-p2p/mqtt';" > mqtt.mjs

for strategy in nostr mqtt; do
	npx esbuild "$strategy.mjs" --bundle --format=esm --minify --platform=browser --target=es2022 \
		--legal-comments=none --metafile="$strategy.meta.json" --outfile="$HERE/trystero-$strategy.js"
done

# The packages bundled, for the licence file
node -e '
const fs = require("fs");
const names = new Set();
for (const file of ["nostr.meta.json", "mqtt.meta.json"]) {
	for (const input of Object.keys(JSON.parse(fs.readFileSync(file, "utf8")).inputs)) {
		const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
		if (match) { names.add(match[1]); }
	}
}
let text = "Third-party licences of trystero-nostr.js and trystero-mqtt.js, generated by bundle-trystero.sh.\n" +
	"mqtt is bundled from its own browser build (dist/mqtt.esm.js), which already contains its dependencies\n" +
	"(buffer, readable-stream, events and others, under MIT, ISC or BSD licences; see mqtt\x27s package.json).\n";
for (const name of [...names].sort()) {
	const dir = "node_modules/" + name;
	const version = JSON.parse(fs.readFileSync(dir + "/package.json", "utf8")).version;
	const licence = fs.readdirSync(dir).find(file => /^licen[cs]e/i.test(file));
	text += "\n" + "=".repeat(80) + "\n" + name + " " + version + "\n" + "=".repeat(80) + "\n\n";
	text += licence ? fs.readFileSync(dir + "/" + licence, "utf8").trim() + "\n" : "(" + JSON.parse(fs.readFileSync(dir + "/package.json", "utf8")).license + ", no licence file in the package)\n";
}
fs.writeFileSync(process.argv[1], text);
' "$HERE/trystero.license.txt"

ls -l "$HERE"/trystero-*.js
