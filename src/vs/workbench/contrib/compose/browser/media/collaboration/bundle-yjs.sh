# Regenerates the vendored Yjs bundle of Compose > Collaboration: yjs.js, an ES module with the parts of Yjs
# that Same Page sessions use to edit a text together (collaborationSamePage.ts imports it, with the types of
# yjs.d.ts). It is generated, never edited by hand; the version is pinned here and in cgmanifest.json.
# Usage: bash bundle-yjs.sh (needs npm; works in a temporary folder).

set -euo pipefail

YJS_VERSION=13.6.33
ESBUILD_VERSION=0.25.12
HERE="$(cd "$(dirname "$0")" && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

cd "$WORK"
npm init -y > /dev/null
npm install --no-audit --no-fund --save-exact "yjs@$YJS_VERSION" "esbuild@$ESBUILD_VERSION" > /dev/null

cat > yjs.mjs <<'EOF'
export {
	Doc, UndoManager, applyUpdateV2, encodeStateAsUpdateV2,
	createRelativePositionFromTypeIndex, createAbsolutePositionFromRelativePosition,
	encodeRelativePosition, decodeRelativePosition,
} from 'yjs';
EOF

npx esbuild yjs.mjs --bundle --format=esm --minify --platform=browser --target=es2022 \
	--legal-comments=none --metafile=yjs.meta.json --outfile="$HERE/yjs.js"

# The packages bundled, for the licence file
node -e '
const fs = require("fs");
const names = new Set();
for (const input of Object.keys(JSON.parse(fs.readFileSync("yjs.meta.json", "utf8")).inputs)) {
	const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
	if (match) { names.add(match[1]); }
}
let text = "Third-party licences of yjs.js, generated by bundle-yjs.sh.\n";
for (const name of [...names].sort()) {
	const dir = "node_modules/" + name;
	const version = JSON.parse(fs.readFileSync(dir + "/package.json", "utf8")).version;
	const licence = fs.readdirSync(dir).find(file => /^licen[cs]e/i.test(file));
	text += "\n" + "=".repeat(80) + "\n" + name + " " + version + "\n" + "=".repeat(80) + "\n\n";
	text += licence ? fs.readFileSync(dir + "/" + licence, "utf8").trim() + "\n" : "(" + JSON.parse(fs.readFileSync(dir + "/package.json", "utf8")).license + ", no licence file in the package)\n";
}
fs.writeFileSync(process.argv[1], text);
' "$HERE/yjs.license.txt"

ls -l "$HERE/yjs.js"
