// Write build/pollis/pollisToml.mjs, Pollis' own panel TOML parser as a plain JavaScript module.
//
//   node build/pollis/makePollisToml.ts            write it
//   node build/pollis/makePollisToml.ts --check    exit 1 if it is out of date
//
// The module is tomlPanelData.ts (parseToml, tomlToPanelData) with its types stripped by Node, so it
// parses a panel TOML exactly as Pollis does at runtime. The Pollis Agents plugin
// (Trumpingtons/pollis-plugins) downloads it from
// https://raw.githubusercontent.com/saragga/pollis/main/build/pollis/pollisToml.mjs
// so its validator and builder never carry a copy of the parser that could drift from Pollis.
// Run it again, and commit the result, whenever tomlPanelData.ts changes.

import * as fs from 'fs';
import * as path from 'path';
import { stripTypeScriptTypes } from 'module';

const ROOT = path.join(import.meta.dirname, '..', '..');
const SOURCE = 'src/vs/workbench/contrib/model/browser/common/tomlPanelData.ts';
const OUT_FILE = path.join(ROOT, 'build', 'pollis', 'pollisToml.mjs');

const source = fs.readFileSync(path.join(ROOT, SOURCE), 'utf-8');
if (/^import (?!type )/m.test(source)) {
	throw new Error(`${SOURCE} has a runtime import: pollisToml.mjs must stay self-contained`);
}
const header = source.match(/^\/\*-+[\s\S]*?-+\*\/\n/)?.[0] ?? '';
const body = stripTypeScriptTypes(source.slice(header.length), { mode: 'strip' })
	// Drop the lines left blank by stripped `import type` declarations
	.replace(/^\s*\n(?=\s*\n)/gm, '');
const output = `${header}
// GENERATED by build/pollis/makePollisToml.ts from ${SOURCE}: do not edit.
// Pollis' panel TOML parser as plain JavaScript, for the Pollis Agents plugin.
${body.replace(/^\n+/, '\n')}`;

if (process.argv.includes('--check')) {
	const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf-8') : '';
	if (current !== output) {
		console.error(`build/pollis/pollisToml.mjs is out of date: run node build/pollis/makePollisToml.ts`);
		process.exit(1);
	}
	console.log('build/pollis/pollisToml.mjs is up to date');
} else {
	fs.writeFileSync(OUT_FILE, output);
	console.log(`wrote build/pollis/pollisToml.mjs`);
}
